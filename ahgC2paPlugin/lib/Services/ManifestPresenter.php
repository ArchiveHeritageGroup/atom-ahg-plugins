declare(strict_types=1);

namespace AhgC2pa\Services;

final class ManifestPresenter
{
    public const STATE_VERIFIED = 'verified';
    public const STATE_INVALID = 'invalid';
    public const STATE_ABSENT = 'absent';

    /**
     * Flatten a manifest into an ordered list of steps, each
     * {kind, label, summary, when, software, params}.
     *
     * @return list<array<string,mixed>>
     */
    public static function readAssertions(mixed $manifest): array
    {
        $assertions = is_array($manifest) ? ($manifest['assertions'] ?? null) : null;
        if (!is_array($assertions)) {
            return [];
        }

        $out = [];
        foreach ($assertions as $a) {
            if (!is_array($a)) {
                continue;
            }
            $label = (string) ($a['label'] ?? '');
            $data = is_array($a['data'] ?? null) ? $a['data'] : [];

            if (str_starts_with($label, 'c2pa.actions')) {
                foreach ((is_array($data['actions'] ?? null) ? $data['actions'] : []) as $action) {
                    if (is_array($action)) {
                        $out[] = self::describeAction($label, $action);
                    }
                }

                continue;
            }

            if ($label === 'c2pa.training-mining') {
                $out[] = self::step('training-mining', $label, self::trainingMiningSummary($data));

                continue;
            }

            if (str_starts_with($label, 'stds.')) {
                $out[] = self::step('metadata', $label, self::metadataSummary($label), null, null, self::scalarParams($data));

                continue;
            }

            $out[] = self::step('other', $label, $label !== '' ? $label : self::t('Declaration'), null, null, self::scalarParams($data));
        }

        return $out;
    }

    /**
     * Font Awesome icon for a step kind.
     */
    public static function icon(string $kind): string
    {
        return match ($kind) {
            'ai'              => 'fa-robot',
            'training-mining' => 'fa-balance-scale',
            'metadata'        => 'fa-tags',
            default           => 'fa-pen',
        };
    }

    /**
     * @param array<string,mixed> $action
     *
     * @return array<string,mixed>
     */
    private static function describeAction(string $label, array $action): array
    {
        $name = (string) ($action['action'] ?? 'action');
        $software = null;
        $sw = $action['softwareAgent'] ?? null;
        if (is_array($sw)) {
            $swName = self::cleanStr($sw['name'] ?? null);
            $swVer = self::cleanStr($sw['version'] ?? null);
            $software = trim((string) $swName . ($swVer !== null ? ' ' . $swVer : '')) ?: null;
        }

        $map = [
            'c2pa.created'   => 'Digitised / created',
            'c2pa.edited'    => 'Edited',
            'c2pa.placed'    => 'Placed into this asset',
            'placed'         => 'Placed into this asset',
            'ai-generated'   => 'Generated by AI',
            'ai-assisted'    => 'AI-assisted edit',
            'c2pa.opened'    => 'Opened',
            'c2pa.converted' => 'Converted',
        ];
        $summary = isset($map[$name])
            ? self::t($map[$name])
            : ucfirst(str_replace(['c2pa.', '-', '_'], ['', ' ', ' '], $name));

        $params = is_array($action['parameters'] ?? null) ? self::scalarParams($action['parameters']) : [];
        $isAi = str_contains($name, 'ai-') || isset($params['model_id']) || isset($params['inferenceStep']);

        $step = self::step($isAi ? 'ai' : 'action', $label, $summary, self::cleanStr($action['when'] ?? null), $software, $params);
        $step['action'] = $name;

        return $step;
    }

    /**
     * @param array<string,string> $params
     *
     * @return array<string,mixed>
     */
    private static function step(string $kind, string $label, string $summary, ?string $when = null, ?string $software = null, array $params = []): array
    {
        return [
            'kind'     => $kind,
            'label'    => $label,
            'summary'  => $summary,
            'when'     => $when,
            'software' => $software,
            'params'   => $params,
        ];
    }

    /**
     * @param array<string,mixed> $data
     *
     * @return array<string,string>
     */
    private static function scalarParams(array $data): array
    {
        $out = [];
        foreach ($data as $k => $v) {
            if (is_scalar($v) && (string) $v !== '') {
                $out[(string) $k] = is_bool($v) ? ($v ? self::t('yes') : self::t('no')) : (string) $v;
            }
        }

        return $out;
    }

    /**
     * @param array<string,mixed> $data
     */
    private static function trainingMiningSummary(array $data): string
    {
        foreach ((is_array($data['entries'] ?? null) ? $data['entries'] : []) as $entry) {
            if (is_array($entry) && ($entry['use'] ?? null) === 'allowed') {
                return self::t('AI training / data mining is permitted on this asset.');
            }
        }

        return self::t('AI training and data mining are not permitted without a licence.');
    }

    private static function metadataSummary(string $label): string
    {
        return match ($label) {
            'stds.exif' => self::t('Embedded EXIF camera/capture metadata.'),
            'stds.iptc' => self::t('Embedded IPTC descriptive / rights metadata.'),
            'stds.xmp'  => self::t('Embedded XMP (Dublin Core / rights) metadata.'),
            default     => self::t('Embedded standard metadata.'),
        };
    }

    public static function cleanStr(mixed $v): ?string
    {
        if (!is_scalar($v)) {
            return null;
        }
        $s = trim((string) $v);

        return $s === '' ? null : $s;
    }

    private static function t(string $s): string
    {
        return function_exists('__') ? (string) __($s) : $s;
    }
}
